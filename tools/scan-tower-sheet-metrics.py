"""Scans every tower sheet for the alpha bounding box of each frame.

Writes src/shared/constants/towerSheetMetrics.generated.ts, so the game sizes and
anchors towers by the drawn structure instead of the empty 60px frame and does no
pixel scans at runtime. Re-run it after any change to public/assets/towers/*.png.

Usage:
    python tools/scan-tower-sheet-metrics.py           # rewrite the generated file
    python tools/scan-tower-sheet-metrics.py --check   # exit 1 if it is stale
"""
import argparse
import hashlib
import re
import sys
from pathlib import Path

try:
    from PIL import Image
except ImportError:  # pragma: no cover - environment guard
    sys.exit('Pillow is required: pip install pillow')

ROOT = Path(__file__).resolve().parent.parent
SPRITES_TS = ROOT / 'src' / 'shared' / 'constants' / 'sprites.ts'
SHEET_DIR = ROOT / 'public' / 'assets' / 'towers'
OUTPUT = ROOT / 'src' / 'shared' / 'constants' / 'towerSheetMetrics.generated.ts'

FRAME_SIZE_PX = 60
COLUMNS = 5
ROWS = 3
# Soft painted edges and faint glows below this alpha do not count as structure.
ALPHA_THRESHOLD = 32


def read_tower_sprite_keys() -> list[str]:
    source = SPRITES_TS.read_text(encoding='utf-8')
    block = re.search(r'export const TOWER_SPRITE_KEYS = \{(.*?)\} as const;', source, re.S)
    if block is None:
        sys.exit(f'TOWER_SPRITE_KEYS not found in {SPRITES_TS}')
    return sorted(re.findall(r"'(tower\.[a-z_]+\.[a-z_]+)'", block.group(1)))


def to_sheet_path(sprite_key: str) -> Path:
    """Mirrors toTowerSheetPath in sprites.ts: tower.orc.tar_pit -> orc_tar_pit.png."""
    return SHEET_DIR / (sprite_key.removeprefix('tower.').replace('.', '_', 1) + '.png')


def scan_frames(sheet: Path) -> list[tuple[int, int, int, int] | None]:
    image = Image.open(sheet).convert('RGBA')
    expected = (FRAME_SIZE_PX * COLUMNS, FRAME_SIZE_PX * ROWS)
    if image.size != expected:
        sys.exit(f'{sheet.name}: expected {expected[0]}x{expected[1]}, got {image.size}')
    mask = image.getchannel('A').point(lambda alpha: 255 if alpha >= ALPHA_THRESHOLD else 0)
    boxes: list[tuple[int, int, int, int] | None] = []
    for frame in range(COLUMNS * ROWS):
        left = (frame % COLUMNS) * FRAME_SIZE_PX
        top = (frame // COLUMNS) * FRAME_SIZE_PX
        box = mask.crop((left, top, left + FRAME_SIZE_PX, top + FRAME_SIZE_PX)).getbbox()
        boxes.append(None if box is None else (box[0], box[1], box[2] - box[0], box[3] - box[1]))
    return boxes


def render() -> str:
    lines = [
        '// Generated by tools/scan-tower-sheet-metrics.py - do not edit by hand.',
        '// Re-run the script after changing any sheet in public/assets/towers.',
        '',
        '/** Alpha bounding box of a frame in frame pixels: x, y, width, height. */',
        'export type TowerSheetFrameBox = readonly [number, number, number, number];',
        '',
        'export type TowerSheetMetrics = {',
        '  /** SHA-256 of the scanned sheet, so a repainted sheet with stale metrics fails a test. */',
        '  sheetSha256: string;',
        '  /** One entry per sheet slot (5x3), null for an empty slot. */',
        '  frameBoxes: readonly (TowerSheetFrameBox | null)[];',
        '};',
        '',
        f'export const TOWER_SHEET_METRICS_ALPHA_THRESHOLD = {ALPHA_THRESHOLD};',
        '',
        'export const TOWER_SHEET_METRICS: Readonly<Record<string, TowerSheetMetrics>> = {',
    ]
    for sprite_key in read_tower_sprite_keys():
        sheet = to_sheet_path(sprite_key)
        if not sheet.exists():
            sys.exit(f'{sprite_key}: missing sheet {sheet}')
        digest = hashlib.sha256(sheet.read_bytes()).hexdigest()
        lines.append(f"  '{sprite_key}': {{")
        lines.append(f"    sheetSha256: '{digest}',")
        lines.append('    frameBoxes: [')
        for box in scan_frames(sheet):
            lines.append('      null,' if box is None else f'      [{box[0]}, {box[1]}, {box[2]}, {box[3]}],')
        lines.append('    ],')
        lines.append('  },')
    lines.append('};')
    lines.append('')
    return '\n'.join(lines)


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument('--check', action='store_true', help='fail if the generated file is stale')
    args = parser.parse_args()
    content = render()
    if args.check:
        current = OUTPUT.read_text(encoding='utf-8') if OUTPUT.exists() else ''
        if current.replace('\r\n', '\n') != content:
            sys.exit(f'{OUTPUT.relative_to(ROOT)} is stale: run python tools/scan-tower-sheet-metrics.py')
        print('tower sheet metrics are current')
        return
    OUTPUT.write_text(content, encoding='utf-8', newline='\n')
    print(f'wrote {OUTPUT.relative_to(ROOT)}')


if __name__ == '__main__':
    main()
